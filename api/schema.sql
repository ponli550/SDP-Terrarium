CREATE TABLE IF NOT EXISTS users    (email TEXT PRIMARY KEY, pass TEXT NOT NULL, home TEXT NOT NULL DEFAULT '{}', set_up INTEGER NOT NULL DEFAULT 0, created INTEGER NOT NULL);
CREATE TABLE IF NOT EXISTS sessions (hash TEXT PRIMARY KEY, email TEXT NOT NULL, exp INTEGER NOT NULL);
CREATE TABLE IF NOT EXISTS fails    (email TEXT PRIMARY KEY, n INTEGER NOT NULL, t INTEGER NOT NULL);
CREATE TABLE IF NOT EXISTS recovery (email TEXT PRIMARY KEY, hash TEXT NOT NULL);
